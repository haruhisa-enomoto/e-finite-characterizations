#!/usr/bin/env python3
"""Generate the standalone Challenge from the maintained Mathlib-only statement."""

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
THEOREM = """
namespace EFiniteCharacterizations.Challenge

/-- Theorem A(I). Seventeen equivalent characterizations over an arbitrary field. -/
theorem arbitraryField : Statement.ArbitraryField.{u} := by
  sorry

/-- Theorem A(II). Finiteness of brick and stable classes with a fixed composition vector. -/
theorem infiniteField : Statement.InfiniteField.{u} := by
  sorry

/-- Theorem A(III). King closed points, open brick orbits and open wide loci in the basic representation varieties. -/
theorem algebraicallyClosedField : Statement.AlgebraicallyClosedField.{u} := by
  sorry

/-- Theorem B. E-finiteness, brick-finiteness and τ-tilting finiteness coincide in rank at most two. -/
theorem rankTwo : Statement.RankTwo.{u} := by
  sorry

/-- Corollary C. Brick-discreteness is equivalent to multiplicity-freeness on every irreducible component. -/
theorem brickDiscreteMultiplicityFree : Statement.BrickDiscreteMultiplicityFree.{u} := by
  sorry

end EFiniteCharacterizations.Challenge
"""


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if Challenge.lean is stale")
    args = parser.parse_args()
    source = (ROOT / "EFiniteCharacterizations/Statement.lean").read_text()
    imports = [line.split()[-1] for line in source.splitlines()
               if line.startswith(("import ", "public import "))]
    if not imports or any(name != "Mathlib" and not name.startswith("Mathlib.") for name in imports):
        raise SystemExit("Statement.lean must import only Mathlib")
    expected = "-- Generated by scripts/generate_challenge.py; edit Statement.lean.\n" + source + THEOREM
    target = ROOT / "Challenge.lean"
    if args.check:
        if not target.exists() or target.read_text() != expected:
            raise SystemExit("Challenge.lean is stale; run scripts/generate_challenge.py")
    else:
        target.write_text(expected)
    print(f"Challenge.lean: {len(expected.splitlines())} lines, {len(expected.encode())} bytes")


if __name__ == "__main__":
    main()
